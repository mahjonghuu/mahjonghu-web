import type { Metadata } from "next";
import { connection } from "next/server";
import { Suspense } from "react";
import { getSiteUrl, serializeJsonLd } from "../lib/seo";
import HomeClient from "./home-client";
import { loadHomeData } from "./home-data";
import type { HomeOutlet } from "./home-types";
import styles from "./page.module.css";

const title = "MahjongHu | Book Mahjong Tables & Venues";
const description =
  "Find MahjongHu venues, explore table rates, and book mahjong tables for your next game with friends.";

/** Canonical and social identity of the public discovery homepage. */
export const metadata: Metadata = {
  alternates: { canonical: "/" },
  description,
  openGraph: {
    title,
    description,
    siteName: "MahjongHu",
    type: "website",
    url: "/",
    images: [
      {
        url: "/opengraph-image",
        width: 1200,
        height: 630,
        alt: "MahjongHu — book mahjong tables and venues",
      },
    ],
  },
};

/** Resolves only a venue's real web photo, never the decorative fallback image. */
function outletImage(photo: string | null, siteUrl: URL): string | undefined {
  if (!photo) return undefined;
  try {
    const url = new URL(photo, siteUrl);
    return url.protocol === "https:" || url.protocol === "http:"
      ? url.href
      : undefined;
  } catch {
    return undefined;
  }
}

/** Builds linked entities only for venues explicitly published by the backend. */
function structuredData(outlets: HomeOutlet[]) {
  const siteUrl = getSiteUrl();
  const organizationId = new URL("/#organization", siteUrl).href;
  const websiteId = new URL("/#website", siteUrl).href;
  const publicOutlets = outlets.filter(
    (outlet) => outlet.visibility === "public" && outlet.active === true,
  );
  const businesses = publicOutlets.map((outlet) => {
    const url = new URL(`/#outlet-${encodeURIComponent(outlet.id)}`, siteUrl)
      .href;
    const image = outletImage(outlet.photo, siteUrl);
    return {
      "@type": "LocalBusiness",
      "@id": url,
      url,
      name: outlet.name,
      address: {
        "@type": "PostalAddress",
        streetAddress: outlet.address,
        addressLocality: outlet.city,
      },
      ...(image ? { image } : {}),
      parentOrganization: { "@id": organizationId },
    };
  });

  return {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebSite",
        "@id": websiteId,
        url: siteUrl.href,
        name: "MahjongHu",
        publisher: { "@id": organizationId },
      },
      {
        "@type": "Organization",
        "@id": organizationId,
        url: siteUrl.href,
        name: "MahjongHu",
        logo: new URL("/logo-transparent.webp", siteUrl).href,
        ...(businesses.length
          ? {
              location: businesses.map((business) => ({
                "@id": business["@id"],
              })),
            }
          : {}),
      },
      ...businesses,
    ],
  };
}

async function HomepageContent() {
  // A per-request request ID is generated by the API client; defer rendering so
  // Next.js never evaluates it during static prerendering.
  await connection();
  const data = await loadHomeData();
  return (
    <>
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{
          __html: serializeJsonLd(structuredData(data.outlets)),
        }}
      />
      <HomeClient {...data} />
    </>
  );
}

/** Public venue discovery with fresh request-time data streamed beneath Suspense. */
export default function Home() {
  return (
    <Suspense
      fallback={
        <main className={styles.page}>
          <p role="status">Loading venues and tables...</p>
        </main>
      }
    >
      <HomepageContent />
    </Suspense>
  );
}
